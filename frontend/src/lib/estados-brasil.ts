export type EstadoUF = (typeof ESTADOS_BRASIL)[number]["uf"];

const UF_SET = new Set<string>(ESTADOS_BRASIL.map((item) => item.uf));

export function isValidEstado(value: string): value is EstadoUF {
  return UF_SET.has(value.trim().toUpperCase());
}

export function normalizeEstado(value: string): EstadoUF | null {
  const uf = value.trim().toUpperCase();
  return isValidEstado(uf) ? uf : null;
}

export function normalizeCidade(value: string) {
  return value.trim().replace(/\s+/g, " ").slice(0, 120);
}
